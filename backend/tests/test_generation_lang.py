# ---- API : défaut = langue de l'interface, ?lang= prioritaire -------------------------------------------------------

@pytest.fixture
def client(tmp_path, monkeypatch):
    monkeypatch.setenv("ONTOFORGE_DATA", str(tmp_path))
    monkeypatch.setenv("ONTOFORGE_LLM_PROVIDER", "mock")
    return TestClient(app)


def _project(c):
    r = c.post("/api/projects", json={"name": "Shop", "sample": "automaint"})
    assert r.status_code == 201, r.text
    return r.json()["id"]


def _set_ui(c, lang):
    r = c.put("/api/settings", json={"language": {"ui": lang, "labels": "fr", "assistant": lang}})
    assert r.status_code == 200, r.text


def test_api_follows_ui_language_and_lang_overrides(client):
    pid = _project(client)
    _set_ui(client, "fr")
    fr = client.get(f"/api/projects/{pid}/generate/neo4j").json()["files"]
    assert "généré par OntoForge" in fr["schema.cypher"] and fr["rapport-transposition.md"].startswith("# Rapport")
    _set_ui(client, "en")
    en = client.get(f"/api/projects/{pid}/generate/neo4j").json()["files"]
    assert "generated by OntoForge" in en["schema.cypher"] and en["rapport-transposition.md"].startswith("# Transposition report")
    assert "README-neo4j.md" in en and en["README-neo4j.md"].startswith("# Neo4j schema")
    # lang explicite : l'anglais malgré une interface française, et inversement
    _set_ui(client, "fr")
    forced = client.get(f"/api/projects/{pid}/generate/curiosity?lang=en").json()["files"]
    assert "Generated by OntoForge" in forced["Schema.cs"] and forced["README-curiosity.md"].startswith("# Curiosity schema")
    _set_ui(client, "en")
    forced_fr = client.get(f"/api/projects/{pid}/generate/curiosity?lang=fr").json()["files"]
    assert "Généré par OntoForge" in forced_fr["Schema.cs"] and forced_fr["rapport-transposition.md"].startswith("# Rapport")
    # zip : même paramètre
    z = client.get(f"/api/projects/{pid}/generate/curiosity/zip?lang=en")
    assert z.status_code == 200 and z.headers["content-type"] == "application/zip"
    # valeur inconnue : refus lisible dans les deux langues
    bad = client.get(f"/api/projects/{pid}/generate/curiosity?lang=de")
    assert bad.status_code == 422 and "fr ou en" in bad.json()["detail"] and "fr or en" in bad.json()["detail"]


def test_ontology_texts_pass_through_untouched_in_english(client):
    """Libellés et commentaires de l'ontologie (ici en français) sont des données : jamais retraduits par fragments."""
    pid = _project(client)
    en = client.get(f"/api/projects/{pid}/generate/curiosity?lang=en").json()["files"]
    fr = client.get(f"/api/projects/{pid}/generate/curiosity?lang=fr").json()["files"]
    comment = "Personne ou organisation intervenant dans la maintenance."
    assert comment in fr["Schema.cs"] and comment in en["Schema.cs"]
    assert "limitée en durée et en kilométrage" in en["Schema.cs"]
    assert "intervenant in la" not in en["Schema.cs"] and "durée and en" not in en["Schema.cs"]
    # les identifiants de code sont identiques dans les deux langues
    cls = lambda t: sorted(re.findall(r"public class (\w+)", t))
    assert cls(en["Schema.cs"]) == cls(fr["Schema.cs"]) and cls(en["Schema.cs"])
    consts = lambda t: sorted(re.findall(r"public const string (\w+)", t))
    assert consts(en["Edges.cs"]) == consts(fr["Edges.cs"])


