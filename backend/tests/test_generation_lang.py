def test_code_and_labels_are_never_translated(files_en):
    onto, pg = _pg("curiosity")
    fr = curiosity.generate(pg, onto)
    with gen.using_lang("en"):
        en = curiosity.generate(pg, onto)
    ident = re.compile(r"^\s*(public|\[|using|namespace|private|foreach|if|var|await|graph|n\.)")
    # identifiants C# : mêmes classes, mêmes propriétés, mêmes constantes d'arêtes dans les deux langues
    for name in ("Schema.cs", "Edges.cs", "RegisterSchema.cs"):
        code = lambda t: [l for l in t.splitlines() if ident.match(l) and "//" not in l.split("{")[0][:3]]
        assert [l for l in code(fr[name]) if "class" in l or "const" in l or "[Key]" in l] == \
               [l for l in code(en[name]) if "class" in l or "const" in l or "[Key]" in l]
    for needle in ("class Vehicle", "class Garage", "class Part", "public const string"):
        assert needle in en["Schema.cs"] + en["Edges.cs"]
    # le libellé de l'ontologie passe tel quel dans le commentaire (donnée)
    assert re.search(r"summary>\s*Vehicle|Vehicle", en["Schema.cs"])


