def test_demo_pdf_generator_takes_a_language(tmp_path):
    import importlib.util
    import pathlib
    root = pathlib.Path(__file__).resolve().parents[2]
    spec = importlib.util.spec_from_file_location("make_cdc_l", root / "samples/automaint/make_cahier_des_charges.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    out = tmp_path / "en.pdf"
    mod.make(out, "en")
    from ontoforge.assistant import document
    txt = " ".join(p.text for p in document.extract("en.pdf", out.read_bytes()).pages)
    assert "Requirements specification" in txt and "Cahier des charges" not in txt
    assert mod.FILENAMES == {"fr": "automaint-cahier-des-charges.pdf", "en": "automaint-requirements.pdf"}
