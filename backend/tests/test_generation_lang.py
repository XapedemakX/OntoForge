def _upload_draft(c, content, name):
    up = c.post("/api/assistant/document/upload", files={"file": (name, content, "application/pdf")})
    assert up.status_code == 200, up.text
    r = c.post("/api/assistant/document/draft", json={"project_id": _project(c), "document": up.json()["document"] if "document" in up.json() else up.json(), "provider_id": "mock"})
    assert r.status_code == 200, r.text
    return r.json()


def test_mock_fallback_questions_follow_ui_language(client):
    from ontoforge.assistant import docheur
    fr_doc = [(1, "Un Véhicule a un numéro VIN. Un Pneu est une Pièce. Un Véhicule est équipé de Pneus. "
                  "Quels véhicules ont un contrôle technique à renouveler ce mois-ci ?")]
    en_doc = [(1, "A Vehicle has a VIN number. A Tyre is a Part. A Vehicle is fitted with Tyres. "
                  "Which vehicles have a technical inspection to renew this month?")]
    # le document dans la langue de l'interface garde ses propres questions
    assert docheur.questions(fr_doc, "fr")[0].startswith("Quels véhicules")
    assert docheur.questions(en_doc, "en")[0].startswith("Which vehicles")
    # un document dans l'autre langue : questions modèles dans la langue de l'interface
    qs_en = docheur.questions(fr_doc, "en")
    assert qs_en and all(q.endswith("?") for q in qs_en) and not any(q.startswith("Quels") for q in qs_en)
    assert any(q.startswith(("Which kinds", "What is recorded", "How is", "What must")) for q in qs_en)
    qs_fr = docheur.questions(en_doc, "fr")
    assert qs_fr and not any(q.startswith("Which") for q in qs_fr)


