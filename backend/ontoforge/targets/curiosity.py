def _schema_cs(plan: _Plan) -> str:
    pg = plan.pg
    L = _header(pg, T("Schema.cs (types de nœuds)", "Schema.cs (node types)"))
    lost = plan.lost_findings()
    if lost:
        L.append(T("// Constats « perdus » (voir le rapport de transposition) :", "// \"Lost\" findings (see the transposition report):"))
        for f in lost:
            choice = f.chosen or f.recommended or T("non arbitré", "not arbitrated")
            L.append(T(f"// LOST {_comment(f.id)} — {_comment(f.title)} — option : {_comment(choice)}",
                       f"// LOST {_comment(f.id)} — {_comment(f.title)} — option: {_comment(choice)}"))
        L.append("")
    L += ["using System;", "using System.Collections.Generic;", "using Curiosity.Library;", "",
          f"namespace {plan.ns}.Schema", "{"]
    for nt in plan.skipped:
        L.append(T(f"    // Type abstrait « {_comment(nt.name)} » non généré (C04) : propriétés fusionnées dans les feuilles.",
                   f"    // Abstract type \"{_comment(nt.name)}\" not generated (C04): properties merged into the leaves."))
    if plan.skipped:
        L.append("")
    first = True
    for name, node in plan.nodes.items():
        nt = node.nt
        if not first:
            L.append("")
        first = False
        remarks = []
        if nt.source:
            remarks.append(T("Source OWL : ", "OWL source: ") + ", ".join(nt.source))
        if nt.discriminator:
            vals = ", ".join(nt.discriminator_values)
            remarks.append(T(f"Héritage aplati (C02) : discriminant {nt.discriminator}", f"Flattened inheritance (C02): discriminator {nt.discriminator}")
                           + (f" ∈ {{{vals}}}" if vals else ""))
        if node.key_note:
            remarks.append(node.key_note)
        summary = nt.description or (plan.comment(nt.source[0]) if nt.source else None) or \
            (plan.label(nt.source[0]) if nt.source else None)
        _doc(L, "    ", summary, remarks)
        L.append("    [Node]")
        L.append(f"    public class {node.cls}")
        L.append("    {")
        members: list[list[str]] = []
        if node.key_synthetic:
            m: list[str] = []
            _doc(m, "        ", T("Clé Curiosity (string, unique, non vide).", "Curiosity key (string, unique, non-empty)."), [node.key_note])
            m.append(f"        [Key] public string {node.key_ident} {{ get; set; }}")
            members.append(m)
        for pl in node.props:
            p = pl.p
            m = []
            remarks = []
            if p.source:
                remarks.append(T(f"Source : {p.source}", f"Source: {p.source}"))
            if _type_note(p.type):
                remarks.append(_type_note(p.type))
            if p.lang:
                remarks.append(T(f"Langue : {p.lang} (D06)", f"Language: {p.lang} (D06)"))
            if p.enum:
                remarks.append(T("Valeurs autorisées : ", "Allowed values: ") + ", ".join(map(str, p.enum))
                               + T(" (contrôle dans le connecteur)", " (checked in the connector)"))
            if p.pattern:
                remarks.append(T(f"Motif : {p.pattern} (contrôle dans le connecteur)", f"Pattern: {p.pattern} (checked in the connector)"))
            if p.required and pl.attr != "Key":
                remarks.append(T("Obligatoire (contrôle dans le connecteur : pas de contrainte d'existence Curiosity)",
                                 "Required (checked in the connector: Curiosity has no existence constraint)"))
            if p.unique and pl.attr != "Key":
                remarks.append(T("Unique (contrôle dans le connecteur : seule la clé est unique côté Curiosity)",
                                 "Unique (checked in the connector: only the key is unique on the Curiosity side)"))
            if pl.renamed_from:
                remarks.append(T(f"Renommée depuis « {pl.renamed_from} » (nom réservé ou en conflit)",
                                 f"Renamed from \"{pl.renamed_from}\" (reserved or conflicting name)"))
            if p.note:
                remarks.append(p.note)
            _doc(m, "        ", p.description or (plan.label(p.source) if p.source else None), remarks)
            m.append(f"        [{pl.attr}] public {pl.cs_type} {pl.ident} {{ get; set; }}")
            members.append(m)
        if node.key_components:
            m = []
            args = ", ".join(f"{c.cs_type} {cs_ident(_lower_first(_bare(c.ident)))}" for c in node.key_components)
            parts = ", ".join(_key_part_expr(c.cs_type, cs_ident(_lower_first(_bare(c.ident))))
                              for c in node.key_components)
            _doc(m, "        ", T("Construit la clé déterministe à partir des composants (K02).", "Builds the deterministic key from its components (K02)."),
                 [T("Ne jamais utiliser d'identifiant aléatoire : la ré-ingestion doit retrouver le même nœud.",
                    "Never use a random identifier: re-ingestion must find the same node again.")])
            m.append(f"        public static string BuildKey({args})")
            m.append(f"            => string.Join(\"|\", new[] {{ {parts} }});")
            m.append("")
            call = ", ".join(c.ident for c in node.key_components)
            m.append(T(f"        /// <summary>Renseigne {node.key_ident} depuis les composants.</summary>",
                       f"        /// <summary>Sets {node.key_ident} from the components.</summary>"))
            m.append(f"        public {node.cls} WithComputedKey() {{ {node.key_ident} = BuildKey({call}); return this; }}")
            members.append(m)
        for i, m in enumerate(members):
            if i:
                L.append("")
            L += m
        L.append("    }")
    if not plan.nodes:
        L.append(T("    // Aucun type de nœud dans le modèle.", "    // No node type in the model."))
    L.append("}")
    return "\n".join(L) + "\n"


def _lower_first(s: str) -> str:
    return s[:1].lower() + s[1:] if s else s


def _key_part_expr(cs_type: str, var: str) -> str:
    if cs_type == "string":
        # '%' d'abord, puis '|' : encodage sans ambiguïté (("a%7Cb","c") et ("a|b","c") restent distincts).
        # Les composants nuls/vides sont rejetés avant BuildKey (voir Ingest*), jamais convertis en "".
        return f'{var}.Replace("%", "%25").Replace("|", "%7C")'
    if cs_type in ("DateTimeOffset",):
        return f'{var}.UtcDateTime.ToString("O", System.Globalization.CultureInfo.InvariantCulture)'
    if cs_type == "DateTime":
        return f'{var}.ToString("O", System.Globalization.CultureInfo.InvariantCulture)'
    if cs_type in ("long", "double"):
        return f"{var}.ToString(System.Globalization.CultureInfo.InvariantCulture)"
    if cs_type == "bool":
        return f'({var} ? "true" : "false")'
    if cs_type.endswith("[]"):
        return f'string.Join(",", {var} ?? System.Array.Empty<{cs_type[:-2]}>())'
    return f"{var}.ToString()"


