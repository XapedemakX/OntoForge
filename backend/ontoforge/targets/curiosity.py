    L += [f"namespace {plan.ns}.Schema", "{",
          T("    /// <summary>Noms d'arêtes Curiosity. Chaque relation est déclarée en paire aller/retour ;",
            "    /// <summary>Curiosity edge names. Each relation is declared as a forward/reverse pair;"),
          T("    /// une arête symétrique est son propre retour. Les arêtes ne portent pas de propriétés.</summary>",
            "    /// a symmetric edge is its own reverse. Edges carry no properties.</summary>"),
          "    public static class Edges", "    {"]
    # Commentaires de provenance par constante.
    usage: dict[str, list[str]] = {}
    for i, e in enumerate(plan.edges):
        rev = plan.edge_reverse[i]
        fwd = plan.edge_fwd[i]
        desc = f"{e.from_} -[{fwd}]-> {e.to} ⇄ {rev}"
        if e.symmetric:
            desc += T(" (symétrique)", " (symmetric)")
        if e.derived:
            desc += T(" (matérialisée)", " (materialized)")
        if e.source:
            desc += f" — {e.source}"
        usage.setdefault(fwd, []).append(desc)
        if e.properties:
            usage[fwd].append(T("LOST propriétés d'arête non supportées par Curiosity : ", "LOST edge properties not supported by Curiosity: ") +
                                 ", ".join(p.name for p in e.properties) + T(" (garder un nœud, R01)", " (keep a node, R01)"))
        if rev != fwd:
            usage.setdefault(rev, []).append(T(f"retour de {fwd} ({e.to} -> {e.from_})", f"reverse of {fwd} ({e.to} -> {e.from_})"))
    first = True
    for name, ident in plan.edge_consts.items():
        if not first:
            L.append("")
        first = False
        for u in usage.get(name, []):
            L.append(f"        // {_comment(u)}")
        L.append(f"        public const string {ident} = nameof({ident});" if _bare(ident) == name
                 else f"        public const string {ident} = {cs_string(name)};")
    if not plan.edge_consts:
        L.append(T("        // Aucune arête dans le modèle.", "        // No edge in the model."))
    L += ["    }", "}"]
    return "\n".join(L) + "\n"


