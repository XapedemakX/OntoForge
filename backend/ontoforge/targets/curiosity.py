def cs_ident(name: str) -> str:
    """Identifiant C# sûr : caractères [A-Za-z0-9_], pas de chiffre en tête, mot-clé échappé par '@'."""
    s = re.sub(r"[^0-9A-Za-z_]", "_", name or "")
    if not s:
        s = "_"
    if s[0].isdigit():
        s = "_" + s
    if s in CS_KEYWORDS:
        s = "@" + s
    return s


def _bare(ident: str) -> str:
    return ident[1:] if ident.startswith("@") else ident


def xml_escape(text: str) -> str:
    return (text or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def cs_string(text: Any) -> str:
    """Littéral chaîne C# (échappement standard)."""
    s = str(text)
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "\\r").replace("\n", "\\n").replace("\t", "\\t")
    return f'"{s}"'


def one_line(text: Optional[str]) -> str:
    return re.sub(r"\s+", " ", text or "").strip()


def _comment(text: str) -> str:
    """Texte sûr dans un commentaire // (pas de retour ligne)."""
    return one_line(text).replace("*/", "* /")


def _doc(lines: list[str], indent: str, summary: Optional[str], remarks: list[str]) -> None:
    summary = one_line(summary)
    remarks = [one_line(r) for r in remarks if one_line(r)]
    if not summary and not remarks:
        return
    if summary:
        lines.append(f"{indent}/// <summary>{xml_escape(summary)}</summary>")
    if remarks:
        lines.append(f"{indent}/// <remarks>")
        for r in remarks:
            lines.append(f"{indent}/// {xml_escape(r)}<br/>")
        lines.append(f"{indent}/// </remarks>")


def _namespace(pg: PGModel) -> str:
    base = profile.node_name(pg.meta.name) if pg.meta.name else "OntoForgeModel"
    return cs_ident(base)


def _lib_version(pg: PGModel) -> str:
    """Version de Curiosity.Library retenue (projet, défaut global ; à défaut valeur d'usine pour un appel direct du générateur)."""
    return ((pg.meta.target_versions or {}).get("curiosity_library") or standards.defaults()["curiosity_library"])


def _version_line(pg: PGModel) -> str:
    v = _lib_version(pg)
    st = standards.status("curiosity_library", v)
    if GL() == "en":
        tail = ("version missing from the reference — TO VERIFY" if st == "unknown" else f"status: {standards.status_label('curiosity_library', v, 'en')}")
        return f"Curiosity.Library {v} ({tail}; versions reference dated {standards.updated()}). Compatibility with the workspace: TO VERIFY."
    tail = ("version absente de la référence — À VÉRIFIER" if st == "unknown" else f"statut : {standards.status_label('curiosity_library', v, 'fr')}")
    return f"Curiosity.Library {v} ({tail} ; référence des versions du {standards.updated()}). Compatibilité avec l'espace de travail : À VÉRIFIER."


def _header(pg: PGModel, what: str) -> list[str]:
    return [
        "// <auto-generated>",
        T(f"// {HEADER_TAG} {pg.meta.ontoforge_version} — cible Curiosity — {what}",
          f"// {_tag()} {pg.meta.ontoforge_version} — Curiosity target — {what}"),
        T(f"// Modèle : {_comment(pg.meta.name or '(sans nom)')}", f"// Model: {_comment(pg.meta.name or '(unnamed)')}")
        + (f" — {_comment(pg.meta.iri)}" if pg.meta.iri else ""),
        T(f"// Version ciblée : {_version_line(pg)}", f"// Target version: {_version_line(pg)}"),
        T("// API : Curiosity.Library (https://docs.curiosity.ai). Les appels non confirmés portent « À VÉRIFIER ».",
          "// API: Curiosity.Library (https://docs.curiosity.ai). Calls that are not confirmed are marked \"TO VERIFY\"."),
        "// </auto-generated>",
        "",
    ]


